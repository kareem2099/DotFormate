import os
import logging
from pymongo import MongoClient
from pymongo.errors import ConnectionFailure, PyMongoError

logger = logging.getLogger(__name__)

class MongoDBManager:
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(MongoDBManager, cls).__new__(cls)
            cls._instance._initialize()
        return cls._instance

    def _initialize(self):
        self.client = None
        self.db = None
        self._connect()

    def _connect(self):
        mongo_uri = os.getenv("MONGO_URI")
        if not mongo_uri:
            logger.error("MONGO_URI not found in .env file. Please set it.")
            return

        try:
            self.client = MongoClient(mongo_uri)
            # The ping command is cheap and does not require auth.
            self.client.admin.command('ping')
            db_name = os.getenv("MONGO_DB_NAME")
            if not db_name:
                logger.error("MONGO_DB_NAME not found in .env file. Please set it.")
                self.client = None
                self.db = None
                return
            self.db = self.client[db_name]
            logger.info("Successfully connected to MongoDB and selected database '%s'!", db_name)
        except ConnectionFailure as e:
            logger.error(f"MongoDB connection failed: {e}")
            self.client = None
            self.db = None
        except PyMongoError as e:
            logger.error(f"An unexpected PyMongo error occurred: {e}")
            self.client = None
            self.db = None

    def get_db(self):
        if self.db is None: # Corrected: Compare with None explicitly
            self._connect() # Attempt to reconnect if not connected
        return self.db

    def close_connection(self):
        if self.client:
            self.client.close()
            logger.info("MongoDB connection closed.")
            self.client = None
            self.db = None

