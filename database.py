async def save_paypal_payment_info(user_id: int, chat_id: int, paypal_payment_id: str) -> bool:
    """
    Saves PayPal payment ID and chat_id for a user.
    This is crucial for linking PayPal webhooks/redirects back to the Telegram user.
    """
    db_manager = MongoDBManager()
    db = db_manager.get_db()
    if db is None:
        logger.error("Database connection not available to save PayPal payment info.")
        return False
    
    users_collection = db.users
    try:
        # Add the payment ID to the user's list of PayPal payment IDs
        # Also ensure chat_id is stored for direct Telegram API calls
        result = users_collection.update_one(
            {"user_id": user_id},
            {"$addToSet": {"paypal_payment_ids": paypal_payment_id},
             "$set": {"chat_id": chat_id}} # Store chat_id for direct messaging
        )
        if result.modified_count > 0:
            logger.info(f"PayPal payment ID {paypal_payment_id} saved for user {user_id}.")
            return True
        else:
            logger.warning(f"PayPal payment ID {paypal_payment_id} not added for user {user_id}. User might not exist or ID already present.")
            return False
    except PyMongoError as e:
        logger.error(f"Error saving PayPal payment info for user {user_id}: {e}")
        return False

