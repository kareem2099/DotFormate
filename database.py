    r2_files_collection = db.r2_files
    try:
        result = await r2_files_collection.update_one(
            {"r2_object_key": r2_object_key},
            {"$set": {"deleted": True}}
        )
        if result.modified_count > 0:
            logger.info(f"R2 file {r2_object_key} marked as deleted in DB.")
            return True
        else:
            logger.warning(f"R2 file {r2_object_key} not found or already marked as deleted in DB.")
            return False
    except PyMongoError as e:
        logger.error(f"Error marking R2 file {r2_object_key} as deleted: {e}")
        return False
