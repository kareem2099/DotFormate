async def increment_daily_conversion_count(user_id: int) -> bool:
    """Increments the daily conversion count for a user, resetting if the day has changed."""
    db_manager = MongoDBManager()
    db = await db_manager.get_db()
    if db is None:
        logger.error("Database connection not available to increment daily conversion count.")
        return False
    
    users_collection = db.users
    today = datetime.utcnow().date()
    
    try:
        user = await get_user(user_id) # Use the existing get_user function
        if not user:
            logger.warning(f"User {user_id} not found for daily conversion count increment.")
            return False

        last_conversion_date = user.get("last_conversion_date")
        daily_conversion_count = user.get("daily_conversion_count", 0)

        # If last_conversion_date is None or a date object, convert it to a datetime object at the start of the day
        if last_conversion_date is None or (isinstance(last_conversion_date, date) and not isinstance(last_conversion_date, datetime)):
            last_conversion_date = datetime.combine(today, time.min)
            # If it was None, treat it as a new day and reset count
            daily_conversion_count = 0
            logger.info(f"User {user_id} had no previous conversion date or it was a date object. Initializing/resetting count to 0.")
            # Update the database immediately to ensure consistency
        await users_collection.update_one(
            {"user_id": user_id},
            {"$set": {
                "daily_conversion_count": daily_conversion_count,
                "last_conversion_date": last_conversion_date
            }}
        )
        return True # Return True as the database was updated

        if last_conversion_date.date() != today: # Compare date parts
            daily_conversion_count = 1 # Reset and start new count
            last_conversion_date = datetime.combine(today, time.min) # Store as datetime object
            logger.info(f"Daily conversion count reset for user {user_id}. New count: 1.")
        else:
            daily_conversion_count += 1
            logger.info(f"Daily conversion count incremented for user {user_id}. New count: {daily_conversion_count}.")

        result = await users_collection.update_one(
            {"user_id": user_id},
            {"$set": {
                "daily_conversion_count": daily_conversion_count,
                "last_conversion_date": last_conversion_date # This will now always be a datetime object
            }}
        )
        return result.modified_count > 0
    except PyMongoError as e:
        logger.error(f"Error incrementing daily conversion count for user {user_id}: {e}")
        return False

